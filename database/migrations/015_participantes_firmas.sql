-- ============================================================
-- SGICO: Migración 015 — Miembros del comité + firmas del acta
-- ============================================================
--
-- OBJETIVO (firma electrónica del acta):
--   Modelo acordado con el usuario:
--     - Existe un LISTADO PREEXISTENTE de miembros del comité, cada uno con su
--       firma escaneada subida de antemano (imagen en Storage).
--     - El acta la maneja UN responsable, que marca quiénes ASISTIERON ese día.
--     - Al cerrar/firmar, el acta estampa automáticamente la firma de cada
--       asistente, con sello de tiempo, hash del contenido y quién la cerró.
--
--   Encuadre legal (Ley 527/1999 + Decreto 2364/2012): firma electrónica simple
--   por atestación del responsable. Se respalda con (1) autorización previa de
--   cada miembro para usar su firma así, (2) fecha_firma, (3) hash_contenido y
--   (4) cerrada_por. La autorización formal se gestiona antes del lanzamiento.
--
-- LO QUE HACE:
--   1. Tabla participantes_comite (roster) con firma_path (Storage).
--   2. Bucket privado 'firmas' + políticas para usuarios autenticados.
--   3. actas_comite: cerrada_por (responsable) + hash_contenido (integridad).
--
-- Ejecutar en: Supabase SQL Editor
-- ============================================================

BEGIN;

-- ============================================================
-- PASO 1 — Roster de miembros del comité
-- ============================================================

CREATE TABLE IF NOT EXISTS participantes_comite (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       text NOT NULL,
  rol          text,
  especialidad text,
  firma_path   text,                       -- ruta en el bucket 'firmas' (NULL = sin firma cargada)
  activo       boolean NOT NULL DEFAULT true,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE participantes_comite ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS auth_all ON participantes_comite;
CREATE POLICY auth_all ON participantes_comite TO authenticated USING (true) WITH CHECK (true);

COMMENT ON TABLE  participantes_comite            IS 'Miembros del comité (roster). Sus firmas escaneadas viven en el bucket firmas.';
COMMENT ON COLUMN participantes_comite.firma_path IS 'Ruta del archivo de firma en Storage (bucket firmas). NULL = sin firma.';
COMMENT ON COLUMN participantes_comite.activo     IS 'Solo los activos aparecen para marcar asistencia en la mesa.';

-- ============================================================
-- PASO 2 — Cierre y firma del acta
-- ============================================================

ALTER TABLE actas_comite
  ADD COLUMN IF NOT EXISTS cerrada_por    text,
  ADD COLUMN IF NOT EXISTS hash_contenido text;

COMMENT ON COLUMN actas_comite.cerrada_por    IS 'Responsable que cerró/firmó el acta (email o id del usuario).';
COMMENT ON COLUMN actas_comite.hash_contenido IS 'SHA-256 del contenido del acta al firmar (evidencia de integridad).';

-- ============================================================
-- PASO 3 — Bucket privado de firmas + políticas
-- ============================================================

INSERT INTO storage.buckets (id, name, public)
VALUES ('firmas', 'firmas', false)
ON CONFLICT (id) DO NOTHING;

DROP POLICY IF EXISTS "firmas auth select" ON storage.objects;
CREATE POLICY "firmas auth select" ON storage.objects
  FOR SELECT TO authenticated USING (bucket_id = 'firmas');

DROP POLICY IF EXISTS "firmas auth insert" ON storage.objects;
CREATE POLICY "firmas auth insert" ON storage.objects
  FOR INSERT TO authenticated WITH CHECK (bucket_id = 'firmas');

DROP POLICY IF EXISTS "firmas auth update" ON storage.objects;
CREATE POLICY "firmas auth update" ON storage.objects
  FOR UPDATE TO authenticated USING (bucket_id = 'firmas') WITH CHECK (bucket_id = 'firmas');

DROP POLICY IF EXISTS "firmas auth delete" ON storage.objects;
CREATE POLICY "firmas auth delete" ON storage.objects
  FOR DELETE TO authenticated USING (bucket_id = 'firmas');

-- ============================================================
-- PASO 4 — Verificación
-- ============================================================

DO $$
DECLARE v int;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.tables
                  WHERE table_schema='public' AND table_name='participantes_comite') THEN
    RAISE EXCEPTION 'ABORT: no se creó participantes_comite';
  END IF;
  SELECT COUNT(*) INTO v FROM information_schema.columns
   WHERE table_schema='public' AND table_name='actas_comite'
     AND column_name IN ('cerrada_por','hash_contenido');
  IF v <> 2 THEN RAISE EXCEPTION 'ABORT: faltan columnas en actas_comite (hay %)', v; END IF;
  IF NOT EXISTS (SELECT 1 FROM storage.buckets WHERE id='firmas') THEN
    RAISE EXCEPTION 'ABORT: no se creó el bucket firmas';
  END IF;
  RAISE NOTICE '════════ MIGRACION 015 COMPLETADA ════════';
  RAISE NOTICE '  participantes_comite (roster + firma_path)';
  RAISE NOTICE '  actas_comite.cerrada_por / hash_contenido';
  RAISE NOTICE '  bucket privado firmas + políticas';
  RAISE NOTICE '═════════════════════════════════════════';
END $$;

COMMIT;
